# Задание 6 (необязательное)
# Напишите программу, которая сможет вычислять площади трех фигур
# (круг, треугольник и прямоугольник).
# ============================================================================

print("=" * 80)
print("ЗАДАНИЕ 6: Вычисление площади фигур")
print("=" * 80)

import math

figure_type = input("Введите тип фигуры:\n").lower()

if figure_type == "круг":
    radius = float(input("Введите радиус круга:\n"))
    area = math.pi * radius ** 2
    print(f"Площадь круга: {area:.2f}")

elif figure_type == "треугольник":
    a = float(input("Введите длину стороны A:\n"))
    b = float(input("Введите длину стороны B:\n"))
    c = float(input("Введите длину стороны C:\n"))
    
    # Используем формулу Герона
    # s - полупериметр
    s = (a + b + c) / 2
    area = math.sqrt(s * (s - a) * (s - b) * (s - c))
    print(f"Площадь треугольника: {area:.2f}")

elif figure_type == "прямоугольник":
    side_a = float(input("Введите длину первой стороны:\n"))
    side_b = float(input("Введите длину второй стороны:\n"))
    area = side_a * side_b
    print(f"Площадь прямоугольника: {area:.2f}")

else:
    print("Ошибка: неизвестный тип фигуры")

print()
