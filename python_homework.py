# Дана переменная, в которой хранится шестизначное число (номер проездного билета).
# Напишите программу, которая будет определять, является ли данный билет "счастливым".
# ============================================================================

print("=" * 80)
print("ЗАДАНИЕ 5: Счастливый билет")
print("=" * 80)

number = 123321

# Преобразуем число в строку для удобства работы с цифрами
number_str = str(number)

# Проверяем, что номер шестизначный
if len(number_str) == 6:
    # Получаем первые три и последние три цифры
    first_three = number_str[:3]
    last_three = number_str[3:]
    
    # Вычисляем суммы
    sum_first = sum(int(digit) for digit in first_three)
    sum_last = sum(int(digit) for digit in last_three)
    
    # Проверяем равенство сумм
    if sum_first == sum_last:
        print("Счастливый билет")
    else:
        print("Несчастливый билет")
else:
    print("Ошибка: номер билета должен быть шестизначным")

print()


